package com.chachamaru.harness.mode;

/**
 * 任务复杂度等级枚举
 * 用于评估任务的复杂程度，作为执行模式推荐的依据
 */
public enum ComplexityLevel {
    /**
     * 简单 - 单一职责，逻辑清晰，风险低
     * 典型场景：格式化代码、简单配置修改、文档更新
     */
    SIMPLE,

    /**
     * 中等 - 需要一定设计，涉及多个模块，风险中等
     * 典型场景：添加单元测试、中等复杂度重构、API 调整
     */
    MODERATE,

    /**
     * 复杂 - 需要深入设计，涉及核心模块，风险较高
     * 典型场景：核心模块重构、架构调整、性能优化
     */
    COMPLEX,

    /**
     * 非常复杂 - 跨系统影响，需要全面测试，风险高
     * 典型场景：架构重构、数据迁移、安全增强
     */
    VERY_COMPLEX
}